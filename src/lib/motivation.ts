export function motivationOfDay(dateIso: string) {
  const d = new Date(dateIso + "T00:00:00Z");
  const day = Math.floor((d.getTime() - Date.UTC(d.getUTCFullYear(), 0, 0)) / 86_400_000) + d.getUTCFullYear() * 7;
  return MOTIVATIONS[day % MOTIVATIONS.length];
}
