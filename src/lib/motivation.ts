/** 1 Januari memakai kalimat pertama dan 31 Desember kalimat ke-365. Di tahun kabisat, 29 Februari mengulang kalimat 28 Februari. */
export function motivationOfDay(dateIso: string) {
  const d = new Date(dateIso + "T00:00:00Z");
  const y = d.getUTCFullYear();
  let day = Math.floor((d.getTime() - Date.UTC(y, 0, 1)) / 86_400_000);
  const leap = (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0;
  if (leap && day >= 59) day -= 1;
  return MOTIVATIONS[Math.min(day, MOTIVATIONS.length - 1)];
}
